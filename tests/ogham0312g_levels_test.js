assert.equal(O.effectBonus(byName('Resonant Litany - Damage'),6),'+5%');
assert.equal(O.effectBonus(byName('Resonant Litany - Damage'),10),'+7%');
assert.equal(O.effectBonus(byName('Downbeat Drop - Damage'),10),'+250%');
