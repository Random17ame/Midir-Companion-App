const state=O.init({});const list=O.activeEffects(state);assert.equal(list.length,97);
const byName=(name)=>list.find(a=>a.en===name);
assert.equal(O.effectBonus(byName('Thunder Max Damage'),1),'+0.12%');
assert.equal(O.effectBonus(byName('Thunder Max Damage'),8),'+0.26%');
assert.equal(O.effectBonus(byName('Thunder Max Damage'),20),'+0.5%');
