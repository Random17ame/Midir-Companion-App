const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const folder=path.join(__dirname,'../Companion Files');
const ctx={window:{},console,Math};vm.createContext(ctx);
for(const name of ['ogham-effect-levels.js','ogham-runes.js'])vm.runInContext(fs.readFileSync(path.join(folder,name),'utf8'),ctx,{filename:name});
const all=ctx.window.MIDIR_OGHAM_CATALOG.abilities,O=ctx.window.MIDIR_OGHAM;
assert.equal(all.length,97);assert.equal(all.filter(a=>a.GeneralPool).length,52);assert.equal(all.filter(a=>!a.GeneralPool).length,45);
