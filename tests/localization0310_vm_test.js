const fs=require('fs'),vm=require('vm'),assert=require('assert');
const root=process.argv[2]||require('path').resolve(__dirname,'..');
const file=require('path').join(root,'Companion Files/i18n.js');
const code=fs.readFileSync(file,'utf8');
let stored='en',output=[];
function CanvasRenderingContext2D(){};
CanvasRenderingContext2D.prototype.fillText=function(t){output.push('fill:'+t)};
CanvasRenderingContext2D.prototype.strokeText=function(t){output.push('stroke:'+t)};
const document={documentElement:{lang:'en'},getElementById:()=>null,createTreeWalker:()=>({nextNode:()=>false}),querySelectorAll:()=>[],body:null};
const window={CanvasRenderingContext2D,MutationObserver:null};
const context={window,document,localStorage:{getItem:()=>stored,setItem:(k,v)=>stored=v},NodeFilter:{SHOW_TEXT:4},Node:{TEXT_NODE:3},console};
vm.runInNewContext(code,context,{filename:'i18n.js'});
const i=window.MIDIR_I18N;
const smoke=(lang,values)=>{i.set(lang);for(const [en,expected] of values)assert.strictEqual(i.t(en),expected,en+' '+lang)};
smoke('es',[['Time Trial','Contrarreloj'],['POWER STRUGGLE','PULSO DE FUERZA'],['Wave 12/50','Oleada 12/50'],['Score 25','Puntuación 25'],['This label is unknown','This label is unknown']]);
smoke('ko',[['Time Trial','시간 제한 도전'],['POWER STRUGGLE','힘겨루기'],['Mana Pressure','마나 압력']]);
smoke('en',[['Time Trial','Time Trial'],['Mana Pressure','Mana Pressure']]);
i.setup();i.set('es');const ctx=new window.CanvasRenderingContext2D();ctx.fillText('Time Trial');ctx.strokeText('Score 25');assert.deepStrictEqual(output,['fill:Contrarreloj','stroke:Puntuación 25']);
i.set('en');ctx.fillText('Time Trial');assert.strictEqual(output[2],'fill:Time Trial');
console.log('Localization 0.3.10 multilingual dictionary + dynamic counter + canvas tests passed');
