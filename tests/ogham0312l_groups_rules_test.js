const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const root=path.resolve(__dirname,'../Companion Files'),ctx={window:{},console};vm.createContext(ctx);
for(const file of ['ogham-effect-levels.js','ogham-runes.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx);
const O=ctx.window.MIDIR_OGHAM;
const s=O.init({runes:[{id:'og-1',word:'Dair',grade:'fine',lines:[],group:'Healing',notes:'keep'},{id:'og-2',word:'Cert',grade:'exquisite',lines:[]},{id:'og-3',word:'Fearn',grade:'masterwork',lines:[]}],simulatedRunes:[{id:'sim-og-1',word:'Ailm',grade:'fine',lines:[]}],loadouts:{hs:['og-1','sim-og-1',null,null,null]},compareLoadouts:{hs:['og-2',null,null,null,null]},nextId:4});
const origIds=O.allRunes(s).map(r=>r.id).join(',');
let block=O.inventoryBlocks(s,'','owned').find(b=>b.type==='group');
assert(block&&block.group.label==='Healing','preexisting text label migrates into visual container');
assert.equal(s.runes[0].notes,'keep');
const oldGroup=block.group.id;
assert(O.assignGroup(s,'og-2',oldGroup));
assert.equal(O.inventoryBlocks(s,'','owned').find(x=>x.group?.id===oldGroup).members.length,2);
const blank=O.createGroup(s,'owned');assert(blank&&!blank.label);
assert(O.assignGroup(s,'og-3',blank.id));assert.equal(O.inventoryBlocks(s,'','owned').filter(x=>x.type==='group').length,2);
assert(O.renameGroup(s,blank.id,'Alternative'));assert(O.moveGroup(s,blank.id,-1));
assert(O.positionRune(s,'owned','og-2','og-3','after'));
assert.equal(s.runes.find(r=>r.id==='og-2').groupId,blank.id);
assert(O.dissolveGroup(s,oldGroup));
assert.equal(s.runes.find(r=>r.id==='og-1').groupId,null);
assert(O.dissolveGroup(s,blank.id));
assert.equal(O.inventoryBlocks(s,'','owned').filter(x=>x.type==='rune').length,3);
const snapshot=JSON.parse(JSON.stringify(s));O.init(snapshot);
assert.equal(O.allRunes(snapshot).map(r=>r.id).join(','),origIds);
assert.equal(snapshot.loadouts.hs[0],'og-1');assert.equal(snapshot.loadouts.hs[1],'sim-og-1');assert.equal(snapshot.compareLoadouts.hs[0],'og-2');
assert.equal(snapshot.runes[0].notes,'keep');
assert.equal(snapshot.inventoryPrefs.containers.owned.length,0);
assert.equal(snapshot.inventoryPrefs.order.filter(x=>x.startsWith('group:')).length,0);
const g=O.createGroup(snapshot,'simulated',['sim-og-1']);assert(g);
assert.equal(O.inventoryBlocks(snapshot,'','simulated').find(x=>x.group?.id===g.id).members.length,1);
assert.equal(snapshot.loadouts.hs[1],'sim-og-1');
console.log('PASS 0.3.12l visual groups: migration, membership, ordering, rename, dissolve, independent inventories, equipment persistence');
