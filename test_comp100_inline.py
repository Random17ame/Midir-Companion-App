from playwright.sync_api import sync_playwright
from pathlib import Path
import re
folder=Path('/mnt/data/_comp100_work')
html=(folder/'index.html').read_text()
html=html.replace('<link rel="stylesheet" href="styles.css">','<style>'+ (folder/'styles.css').read_text()+'</style>')
html=re.sub(r'<script src="([\w.-]+\.js)"></script>',lambda m:'<script>'+ (folder/m.group(1)).read_text().replace('</script>','<\\/script>')+'</script>',html)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=b.new_page(viewport={'width':1280,'height':920},accept_downloads=True)
 err=[];page.on('pageerror', lambda e:err.append(str(e)))
 page.goto('about:blank')
 page.evaluate("""() => { const mem = new Map(); Object.defineProperty(window, 'localStorage',{configurable:true,value:{getItem:k=>mem.has(k)?mem.get(k):null,setItem:(k,v)=>mem.set(k,String(v)),removeItem:k=>mem.delete(k),key:i=>Array.from(mem.keys())[i],get length(){return mem.size}}}); }""")
 page.set_content(html,wait_until='domcontentloaded',timeout=20000)
 page.wait_for_timeout(1000)
 print('TITLE',page.title())
 print('HEADER',page.locator('.header-right .tag').inner_text())
 print('ERRORS',err[:8])
 page.locator('nav [data-page="rotation"]').click()
 print('ARCANA SELECT',page.locator('.rotation-arcana-picker select').count())
 page.locator('.rotation-arcana-picker select').select_option('fa')
 print('FA TILES',page.locator('.rotation-shortcut').all_inner_texts())
 page.locator('[data-act="hub:herbs"]').click()
 print('HERB',page.locator('#herb-pick').count())
 prev=page.evaluate('window.MIDIR_HERBS.getState().total')
 page.locator('#herb-pick').click()
 print('FREE',prev,page.evaluate('window.MIDIR_HERBS.getState().total'))
 page.locator('#herb-mode-challenge').click()
 print('CHALLENGE MODE',page.locator('#herb-start').inner_text())
 page.locator('#herb-duration').select_option('30')
 page.locator('#herb-start').click()
 print('CHALLENGE START',page.locator('#herb-pick').count())
 page.locator('#herb-pick').click()
 print('CHALLENGE PICK',page.locator('#herb-score').inner_text())
 page.wait_for_timeout(2800)
 print('EXPIRED',page.locator('#herb-expired').inner_text())
 page.locator('#herb-end').click()
 print('CHALLENGE RESULT',page.locator('#herb-gather-status').inner_text())
 page.screenshot(path='/mnt/data/_comp100_work/qa-herbs.png',full_page=True)
 page.locator('[data-act="hub:home"]').click()
 page.locator('.rotation-arcana-picker select').select_option('ek')
 print('EK TILES',page.locator('.rotation-shortcut').all_inner_texts())
 page.locator('[data-act="hub:pig"]').click()
 print('CANVAS',page.locator('#ek-pig-canvas').count())
 page.screenshot(path='/mnt/data/_comp100_work/qa-pig-before.png',full_page=True)
 page.locator('#ek-pig-start').click()
 box=page.locator('#ek-pig-canvas').bounding_box()
 page.mouse.move(box['x']+box['width']*.66,box['y']+box['height']*.55)
 page.wait_for_timeout(1550)
 print('PIG TIME',page.locator('#ek-pig-time').inner_text(),'CUE',page.locator('#ek-pig-cue').inner_text())
 page.screenshot(path='/mnt/data/_comp100_work/qa-pig-running.png',full_page=True)
 page.locator('#ek-pig-stop').click()
 print('RECORD',page.evaluate('window.MIDIR_PIG.exportState()'))
 page.locator('[data-act="hub:home"]').click()
 page.locator('.rotation-arcana-picker select').select_option('fa')
 page.locator('[data-act="hub:herbs"]').click()
 print('CHEST STILL',page.evaluate('window.MIDIR_HERBS.getState().total'))
 print('SCORES',page.evaluate('window.MIDIR_HERBS.exportState().challenge'))
 print('FINAL ERRORS',err)
 b.close()
