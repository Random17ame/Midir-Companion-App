from playwright.sync_api import sync_playwright
import json,time
BASE='file:///mnt/data/_comp100_work/index.html'
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage','--allow-file-access-from-files'])
    page=browser.new_page(viewport={'width':1280,'height':920},accept_downloads=True)
    errors=[]
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(BASE,wait_until='domcontentloaded',timeout=25000)
    page.wait_for_timeout(500)
    print('TITLE',page.title())
    print('HEADER',page.locator('.header-right .tag').inner_text())
    print('ERRORS', errors[:10])
    print('NAV',page.locator('nav button').all_text_contents())
    page.locator('nav [data-page="rotation"]').click()
    print('ROTATION TEXT',page.locator('#app').inner_text()[:150])
    print('ARCANA SELECT',page.locator('.rotation-arcana-picker select').count())
    page.locator('.rotation-arcana-picker select').select_option('fa')
    print('FA tiles',page.locator('.rotation-shortcut').all_inner_texts())
    page.locator('[data-act="hub:herbs"]').click()
    print('HERB TITLE',page.locator('h2').all_inner_texts()[:4])
    print('HERB BUTTON',page.locator('#herb-pick').count())
    before=page.evaluate('window.MIDIR_HERBS.getState().total')
    page.locator('#herb-pick').click()
    after=page.evaluate('window.MIDIR_HERBS.getState().total')
    print('FREE GATHER',before,after)
    page.locator('#herb-mode-challenge').click()
    print('CHALLENGE BEFORE',page.locator('#herb-pick').count(),page.locator('#herb-start').inner_text())
    page.locator('#herb-duration').select_option('30')
    page.locator('#herb-start').click()
    print('CHALLENGE START',page.locator('#herb-pick').count(),page.locator('#herb-time').inner_text())
    page.locator('#herb-pick').click()
    print('SCORE AFTER PICK',page.locator('#herb-score').inner_text())
    page.wait_for_timeout(2750)
    print('EXPIRED AFTER WAIT',page.locator('#herb-expired').inner_text())
    page.locator('#herb-end').click()
    print('RESULT',page.locator('#herb-gather-status').inner_text(),page.locator('.herb-best-grid').inner_text())
    print('RECORD',page.evaluate('window.MIDIR_HERBS.exportState().challenge'))
    page.screenshot(path='/mnt/data/_comp100_work/qa-herbs.png',full_page=True)
    page.locator('[data-act="hub:home"]').click()
    page.locator('.rotation-arcana-picker select').select_option('ek')
    print('EK tiles',page.locator('.rotation-shortcut').all_inner_texts())
    page.locator('[data-act="hub:pig"]').click()
    print('PIG CANVAS',page.locator('#ek-pig-canvas').count())
    page.screenshot(path='/mnt/data/_comp100_work/qa-pig-before.png',full_page=True)
    page.locator('#ek-pig-start').click()
    print('PIG START DISABLED',page.locator('#ek-pig-start').is_disabled())
    box=page.locator('#ek-pig-canvas').bounding_box()
    page.mouse.move(box['x']+box['width']*.66,box['y']+box['height']*.55)
    page.wait_for_timeout(1250)
    print('PIG TIME',page.locator('#ek-pig-time').inner_text(),'CUE',page.locator('#ek-pig-cue').inner_text())
    page.screenshot(path='/mnt/data/_comp100_work/qa-pig-running.png',full_page=True)
    page.locator('#ek-pig-stop').click()
    print('PIG RECORD',page.evaluate('window.MIDIR_PIG.exportState()'))
    page.locator('[data-act="hub:home"]').click()
    page.locator('.rotation-arcana-picker select').select_option('fa')
    page.locator('[data-act="hub:herbs"]').click()
    print('PERSIST CHEST',page.evaluate('window.MIDIR_HERBS.getState().total'))
    page.reload(wait_until='domcontentloaded')
    page.wait_for_timeout(250)
    print('RELOAD RECORD',page.evaluate('window.MIDIR_HERBS.exportState().challenge'),page.evaluate('window.MIDIR_PIG.exportState()'))
    print('FINAL ERRORS',errors)
    browser.close()
